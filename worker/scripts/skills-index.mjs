#!/usr/bin/env node
// Write worker/src/skills-index.ts from skills/*/SKILL.md: each skill's frontmatter name and description and the
// sha256 of its exact bytes. GET /.well-known/agent-skills/index.json serves these with version-pinned URLs, so the
// Worker never bundles a SKILL.md body. `npm run version:set` regenerates it after it bumps metadata.version in the
// skills; `--check` exits 1 when the committed file is stale (worker/test/skills-index.test.ts runs the same check).
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const DEFAULT_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
export const OUTPUT = "worker/src/skills-index.ts";

function field(fm, key, rel) {
	const m = fm.match(new RegExp(`^${key}:[ \\t]*(.*)$`, "m"));
	const value = m ? m[1].trim().replace(/^(["'])([\s\S]*)\1$/, "$2") : "";
	if (!value) throw new Error(`${rel}: frontmatter ${key} is missing`);
	return value;
}

/** One entry per skills/<dir>/SKILL.md, sorted by directory name. */
export function skillEntries(root = DEFAULT_ROOT) {
	const dir = path.join(root, "skills");
	return fs.readdirSync(dir).sort().filter((d) => fs.existsSync(path.join(dir, d, "SKILL.md"))).map((d) => {
		const rel = `skills/${d}/SKILL.md`;
		const bytes = fs.readFileSync(path.join(root, rel));
		const m = bytes.toString("utf8").match(/^---\r?\n([\s\S]*?)\r?\n---/);
		if (!m) throw new Error(`${rel}: no frontmatter`);
		const name = field(m[1], "name", rel);
		if (name !== d) throw new Error(`${rel}: frontmatter name ${JSON.stringify(name)} differs from its directory`);
		return { name, description: field(m[1], "description", rel), digest: "sha256:" + crypto.createHash("sha256").update(bytes).digest("hex") };
	});
}

export function render(entries) {
	return "// Generated by worker/scripts/skills-index.mjs from skills/*/SKILL.md. Do not edit; run `node worker/scripts/skills-index.mjs`.\n" +
		"/** The canonical skills: frontmatter name and description, and the sha256 of the SKILL.md bytes at this build's VERSION. */\n" +
		`export const SKILLS: readonly { name: string; description: string; digest: string }[] = ${JSON.stringify(entries, null, "\t")};\n`;
}

/** Write (or, with check, compare) the generated file. Returns true when it was already current. */
export function writeSkillsIndex(root = DEFAULT_ROOT, { check = false } = {}) {
	const dest = path.join(root, OUTPUT);
	const body = render(skillEntries(root));
	const current = fs.existsSync(dest) && fs.readFileSync(dest, "utf8") === body;
	if (!current && !check) fs.writeFileSync(dest, body);
	return current;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	const check = process.argv.includes("--check");
	if (!writeSkillsIndex(DEFAULT_ROOT, { check }) && check) {
		console.error(`skills-index: ${OUTPUT} is stale; run node worker/scripts/skills-index.mjs and commit it`);
		process.exit(1);
	}
}
