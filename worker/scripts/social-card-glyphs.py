#!/usr/bin/env python3
"""Regenerate worker/src/social-card-glyphs.ts, the glyph masks the per-agent social card draws with.

Dev-only. Needs Pillow and the JetBrains Mono (SIL OFL 1.1) Latin WOFF2 files at weights 500 and 700:

  python3 -I worker/scripts/social-card-glyphs.py <dir with jetbrains-mono-latin-{500,700}-normal.woff2>

Sizes and positions match the shared card (`og-card-v1.png`): the prompt line is 700 at 30px with its origin
at x=117, and the footer is 500 at 17px with 0.75px tracking at (89, 545). Only alpha masks are stored; the
Worker colours them at render time.
"""
import base64, os, sys, zlib
from PIL import Image, ImageDraw, ImageFont

# Hostname characters, the ellipsis for very long addresses, and the "Connect to " words.
CHARS = "abcdefghijklmnopqrstuvwxyz0123456789.-:…C "
SIZES = (30, 25, 20)  # integer advances (0.6 em): 18, 15 and 12 px
PAD = 4  # ink may overhang the advance box
CENTER_Y = 371.4  # x-height centre of the prompt line; fitted pixel-for-pixel to the shared card
FOOTER_OFF = "New connection requests are turned off."


def glyph_set(font_path, size):
	font = ImageFont.truetype(font_path, size)
	adv = round(font.getlength("a"))
	assert abs(font.getlength("a") - adv) < 1e-6, "advance must be an integer"
	ascent, descent = font.getmetrics()
	height = ascent + descent + 2 * PAD
	width = adv + 2 * PAD
	# Centre the x-height band ("x" ink) on CENTER_Y, like the shared card's line.
	_, top, _, bottom = font.getbbox("x", anchor="ls")
	baseline = PAD + ascent
	top_y = round(CENTER_Y - (top + bottom) / 2 - baseline)  # canvas y where the cell's row 0 lands
	masks = bytearray()
	for ch in CHARS:
		cell = Image.new("L", (width, height), 0)
		ImageDraw.Draw(cell).text((PAD, baseline), ch, font=font, fill=255, anchor="ls")
		masks += cell.tobytes()
	return {"size": size, "advance": adv, "width": width, "height": height, "top": top_y, "masks": bytes(masks)}


def footer_mask(font_path):
	# Whole-pixel glyph positions with hinting matched the browser-rendered card more closely than supersampling.
	font = ImageFont.truetype(font_path, 17)
	adv = font.getlength("a") + 0.75
	width = int(len(FOOTER_OFF) * adv) + 2 * PAD
	height = 30
	img = Image.new("L", (width, height), 0)
	draw = ImageDraw.Draw(img)
	for i, ch in enumerate(FOOTER_OFF):
		draw.text((PAD + i * adv, 0), ch, font=font, fill=255)
	return {"x": 89 - PAD, "y": 545, "width": width, "height": height, "mask": img.tobytes()}


def main():
	fonts = sys.argv[1]
	bold = os.path.join(fonts, "jetbrains-mono-latin-700-normal.woff2")
	medium = os.path.join(fonts, "jetbrains-mono-latin-500-normal.woff2")
	sets = [glyph_set(bold, s) for s in SIZES]
	footer = footer_mask(medium)
	blob = b"".join(s["masks"] for s in sets) + footer["mask"]
	meta = [{k: s[k] for k in ("size", "advance", "width", "height", "top")} for s in sets]
	out = os.path.join(os.path.dirname(__file__), "..", "src", "social-card-glyphs.ts")
	with open(out, "w") as f:
		f.write("// Generated by worker/scripts/social-card-glyphs.py. Do not edit.\n")
		f.write("// Alpha masks rasterized from JetBrains Mono (SIL Open Font License 1.1) for the per-agent social card.\n")
		f.write(f"export const GLYPH_CHARS = {CHARS!r};\n".replace("'", '"').replace("\\u2026", "…"))
		f.write("export const GLYPH_SETS = [\n")
		for m in meta:
			f.write(f"\t{{ size: {m['size']}, advance: {m['advance']}, width: {m['width']}, height: {m['height']}, top: {m['top']} }},\n")
		f.write("] as const;\n")
		f.write(f"export const GLYPH_PAD = {PAD};\n")
		f.write(f"export const FOOTER_OFF = {{ x: {footer['x']}, y: {footer['y']}, width: {footer['width']}, height: {footer['height']} }} as const;\n")
		f.write("/** zlib: every glyph set's masks in GLYPH_SETS order, then the FOOTER_OFF mask. */\n")
		f.write(f'export const GLYPH_MASKS = "{base64.b64encode(zlib.compress(blob, 9)).decode()}";\n')
	print(out, len(blob), "bytes raw")


if __name__ == "__main__":
	main()
